"""
Stub connector implementations.

Each stub returns realistic, deterministic-ish fake data so the whole
pipeline and UI work end-to-end without any external service. Every stub
reports ``is_stub=True`` from ``health_check`` so the UI can clearly mark
integrations as "not yet connected".
"""
